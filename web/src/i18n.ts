const hasOwn = (obj: unknown, key: string): boolean =>
  typeof obj === 'object' && obj !== null && Object.prototype.hasOwnProperty.call(obj, key)

export const t = (locale: Locale, path: string, vars?: Record<string, string | number>): string => {
  const parts = path.split('.')
  let node: unknown = dicts[locale]
  for (const part of parts) {
    if (!hasOwn(node, part)) {
      node = dicts['zh-Hant']
      for (const fallback of parts) {
        if (!hasOwn(node, fallback)) return path
        node = (node as Dict)[fallback]
      }
      break
    }
    node = (node as Dict)[part]
  }
  if (typeof node !== 'string') return path
  if (!vars) return node
  return node.replace(/\{\{(\w+)\}\}/g, (_, key: string) => (vars[key] != null ? String(vars[key]) : ''))
}

